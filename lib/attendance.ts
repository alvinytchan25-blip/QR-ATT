import { getEventByCode, getEventsByTeacher } from './events';
import { parseQRPayload } from './qr';
import { supabase } from './supabase';

export type AttendanceRecord = {
  id: string;
  eventId: string;
  eventTitle: string;
  scannedAt: string;
};

export type RegisterResult = {
  success: boolean;
  message: string;
  eventTitle?: string;
};

export type TeacherEventAttendance = {
  eventId: string;
  eventCode: string;
  title: string;
  startTime: string | null;
  endTime: string | null;
  attendeeCount: number;
  attendees: {
    studentId: string;
    scannedAt: string;
    studentName?: string;
  }[];
};

export type TeacherEventSummary = {
  eventId: string;
  eventCode: string;
  title: string;
  attendeeCount: number;
};

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

function toTime(value: string | undefined): number | null {
  if (!value) return null;
  const time = new Date(value).getTime();
  // NaN is falsy, so an unparseable date would otherwise skip the check.
  return Number.isNaN(time) ? null : time;
}

export async function registerAttendance(
  rawPayload: string,
  studentId: string
): Promise<RegisterResult> {
  if (!UUID_RE.test(studentId)) {
    return { success: false, message: 'You must be signed in to record attendance.' };
  }

  const parsed = parseQRPayload(rawPayload);
  if (!parsed.ok) {
    return { success: false, message: parsed.message };
  }
  const payload = parsed.payload;

  const now = Date.now();
  const start = toTime(payload.start);
  const end = toTime(payload.end);

  if (start !== null && now < start) {
    return { success: false, message: 'Event has not started yet.' };
  }
  if (end !== null && now > end) {
    return { success: false, message: 'Event has already ended.' };
  }

  const title = payload.title ?? payload.event;
  let event: { id: string; title: string } | null = null;

  const foundEvent = await getEventByCode(payload.event);
  if (foundEvent) {
    event = foundEvent;
  } else {
    // Unknown event code. Only a teacher may insert events (RLS), so this
    // usually means the QR was not generated by this app.
    const { data: newEvent, error: insertError } = await supabase
      .from('events')
      .insert([
        {
          event_code: payload.event,
          title,
          start_time: payload.start ?? null,
          end_time: payload.end ?? null,
        },
      ])
      .select('id, title')
      .single();

    if (insertError || !newEvent) {
      return {
        success: false,
        message: 'This event has not been set up by a teacher yet.',
      };
    }
    event = newEvent;
  }

  const { error: attError } = await supabase.from('attendance').insert([
    {
      student_id: studentId,
      event_id: event.id,
    },
  ]);

  if (attError) {
    if (attError.code === '23505') {
      return {
        success: false,
        message: 'Already registered for this event.',
        eventTitle: event.title,
      };
    }
    // RLS raises 42501 when the row fails the policy's with-check clause,
    // which for attendance means the event window is not open right now.
    if (attError.code === '42501') {
      return {
        success: false,
        message: 'Attendance is not open for this event right now.',
        eventTitle: event.title,
      };
    }
    return { success: false, message: attError.message, eventTitle: event.title };
  }

  return { success: true, message: 'Attendance recorded!', eventTitle: event.title };
}

export async function getAttendanceHistory(
  studentId: string
): Promise<AttendanceRecord[]> {
  const { data, error } = await supabase
    .from('attendance')
    .select('id, scanned_at, events ( event_code, title )')
    .eq('student_id', studentId)
    .order('scanned_at', { ascending: false });

  if (error || !data) {
    return [];
  }

  return (data as any[]).map((row) => ({
    id: row.id,
    eventId: row.events?.event_code ?? '',
    eventTitle: row.events?.title ?? '',
    scannedAt: row.scanned_at,
  }));
}

export async function getTeacherEventAttendance(
  teacherId: string
): Promise<TeacherEventAttendance[]> {
  const events = await getEventsByTeacher(teacherId);
  if (events.length === 0) return [];

  const eventIds = events.map((e) => e.id);

  const { data: attendance, error: attError } = await supabase
    .from('attendance')
    .select('student_id, scanned_at, event_id, profiles ( full_name, email )')
    .in('event_id', eventIds)
    .order('scanned_at', { ascending: false });

  const empty = (e: any): TeacherEventAttendance => ({
    eventId: e.id,
    eventCode: e.event_code,
    title: e.title,
    startTime: e.start_time,
    endTime: e.end_time,
    attendeeCount: 0,
    attendees: [],
  });

  if (attError || !attendance) {
    return (events as any[]).map(empty);
  }

  return (events as any[]).map((e) => {
    const rows = (attendance as any[]).filter((a) => a.event_id === e.id);
    return {
      eventId: e.id,
      eventCode: e.event_code,
      title: e.title,
      startTime: e.start_time,
      endTime: e.end_time,
      attendeeCount: rows.length,
      attendees: rows.map((a) => ({
        studentId: a.student_id,
        scannedAt: a.scanned_at,
        // PostgREST returns an object for a many-to-one embed.
        studentName: a.profiles?.full_name ?? undefined,
      })),
    };
  });
}

export async function getTeacherEventSummary(
  teacherId: string
): Promise<TeacherEventSummary[]> {
  const { data: events, error: eventError } = await supabase
    .from('events')
    .select('id, event_code, title')
    .eq('created_by', teacherId)
    .order('created_at', { ascending: false });

  if (eventError || !events || events.length === 0) {
    return [];
  }

  const eventIds = (events as any[]).map((e) => e.id);

  const { data: attRows, error: attError } = await supabase
    .from('attendance')
    .select('event_id')
    .in('event_id', eventIds);

  if (attError || !attRows) {
    return (events as any[]).map((e) => ({
      eventId: e.id,
      eventCode: e.event_code,
      title: e.title,
      attendeeCount: 0,
    }));
  }

  const counts: Record<string, number> = {};
  (attRows as any[]).forEach((r) => {
    counts[r.event_id] = (counts[r.event_id] ?? 0) + 1;
  });

  return (events as any[]).map((e) => ({
    eventId: e.id,
    eventCode: e.event_code,
    title: e.title,
    attendeeCount: counts[e.id] ?? 0,
  }));
}
